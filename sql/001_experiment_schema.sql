CREATE TABLE IF NOT EXISTS "EXPERIMENT_SESSION" (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    participant_code VARCHAR(120),
    "group" VARCHAR(1) NOT NULL CHECK ("group" IN ('A', 'B')),
    consent_given_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    exported_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    time_to_cv_min DOUBLE PRECISION,
    esco_coverage_pct DOUBLE PRECISION,
    ats_score DOUBLE PRECISION,
    satisfaction DOUBLE PRECISION,
    edits INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS "EVENT_LOG" (
    id BIGSERIAL PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES "EXPERIMENT_SESSION" (id) ON DELETE CASCADE,
    event_type VARCHAR(40) NOT NULL,
    detail TEXT,
    metadata_json JSONB,
    ts TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "SKILL" (
    id BIGSERIAL PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES "EXPERIMENT_SESSION" (id) ON DELETE CASCADE,
    input_label VARCHAR(200) NOT NULL,
    esco_uri VARCHAR(500),
    preferred_label VARCHAR(300),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "SURVEY_RESPONSE" (
    id BIGSERIAL PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES "EXPERIMENT_SESSION" (id) ON DELETE CASCADE,
    question VARCHAR(300) NOT NULL,
    score INTEGER NOT NULL CHECK (score BETWEEN 1 AND 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "APPLICATION_STATUS" (
    id BIGSERIAL PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES "EXPERIMENT_SESSION" (id) ON DELETE CASCADE,
    status VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS event_log_session_ts_idx ON "EVENT_LOG" (session_id, ts DESC);
CREATE INDEX IF NOT EXISTS skill_session_idx ON "SKILL" (session_id);
